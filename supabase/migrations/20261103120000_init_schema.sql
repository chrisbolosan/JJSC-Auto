drop table if exists
  public."RECEIVING_LOG",
  public."ORDER_ITEMS",
  public."ORDERS",
  public."INVENTORY",
  public."CUSTOMER",
  public."SHIPPING_BRACKET",
  public."LEGACY"
cascade;

-- legacy
create table public.parts (
  number integer primary key,
  description text not null,
  price numeric(8, 2) not null,
  weight numeric(4, 2) not null,
  "pictureURL" text
);


-- our DB
create table public.inventory (
  part_number integer primary key,
  quantity integer not null default 0 check (quantity >= 0)
);

create table public.part_categories (
  part_number integer primary key,
  category text not null
);

create table public.customers (
  id bigint generated by default as identity primary key,
  email text not null unique,
  name text not null,
  street text not null,
  city text not null,
  zip_code text not null
);

create table public.orders (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers (id),
  status text not null default 'authorized' check (status in ('authorized', 'shipped')),
  total_weight numeric(8, 2) not null,
  subtotal numeric(10, 2) not null,
  shipping numeric(10, 2) not null,
  total numeric(10, 2) not null,
  auth_number text not null, 
  created_at timestamptz not null default now(),
  shipped_at timestamptz
);

create table public.order_items (
  order_id bigint not null references public.orders (id) on delete cascade,
  part_number integer not null,
  quantity integer not null check (quantity > 0),
  price numeric(8, 2) not null,
  primary key (order_id, part_number)
);

-- ADMIN ONLY CREATION the brackets
create table public.shipping_brackets (
  id bigint generated by default as identity primary key,
  min_weight numeric(8, 2) not null default 0,
  max_weight numeric(8, 2), -- null = no upper limit
  shipping_charge numeric(10, 2) not null
);

-- DELIVERY LOGS
create table public.receiving_log (
  id bigint generated by default as identity primary key,
  part_number integer not null,
  quantity integer not null check (quantity > 0),
  received_at timestamptz not null default now()
);

-- LOCK TABLE
alter table public.parts enable row level security;
